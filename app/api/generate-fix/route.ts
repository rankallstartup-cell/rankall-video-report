import { NextRequest, NextResponse } from "next/server";
import { getCountryConfig, resolveCountryFromRequest } from "@/lib/countryConfig";
import { validateNoFakeData, getFixMetadata } from "@/lib/fixQuality";
import { fixTypeLabel, safeBusinessName, canonicalFixImpact } from "@/lib/fixIntelligence";
import { generateFixContent, generateFixForScan } from "@/lib/generateFix";
import { createServerClient } from "@supabase/ssr";
import { createClient } from "@supabase/supabase-js";

export async function POST(req: NextRequest) {
  try {
    const { fixType, businessInput, industry, location, countryCode, autoGenerated, scanId, userId, city, score, competitorName, competitorScore, revenueGap } = await req.json();

    if (!fixType || !businessInput) {
      return NextResponse.json({ error: "Missing required fields" }, { status: 400 });
    }

    const resolvedCountry = (countryCode && getCountryConfig(countryCode).code === countryCode)
      ? countryCode
      : resolveCountryFromRequest(req.headers);

    // Knowledge Panel — tailored prompt, manual-only (not part of the auto top-3).
    if (fixType === 'knowledge_panel') {
      const bizName = typeof businessInput === 'string' ? businessInput : (businessInput as Record<string, unknown>)?.name ?? businessInput;
      const entityType = (businessInput as Record<string, unknown>)?.entity_type ?? 'business';
      const prompt = `You are an expert in Google Knowledge Graph optimization. Generate a complete Knowledge Panel establishment kit.

Entity: ${bizName}
Type: ${entityType}
Industry/Specialty: ${industry}
City: ${location}
Country: ${resolvedCountry}

IMPORTANT: This is a DRAFT kit for the user to review. All content must be accurate and factual. Do not invent credentials or achievements.

Generate these sections: 1) ENTITY ELIGIBILITY CHECK, 2) WIKIDATA ENTRY TEMPLATE (labelled DRAFT), 3) ENTITY DESCRIPTION (150-160 chars), 4) CITATION BUILDING PLAN (15 directories for this industry/country), 5) STEP-BY-STEP GUIDE (with realistic 6-12 week timeline), 6) WHAT CHANGES FOR AI PLATFORMS.`;

      const fixRes = await fetch('https://api.anthropic.com/v1/messages', {
        method: 'POST',
        headers: { 'x-api-key': process.env.ANTHROPIC_API_KEY!, 'anthropic-version': '2023-06-01', 'Content-Type': 'application/json' },
        body: JSON.stringify({ model: 'claude-haiku-4-5', max_tokens: 2000, messages: [{ role: 'user', content: prompt }] }),
      });
      const fixData = await fixRes.json();
      const fixContent = fixData.content?.[0]?.text ?? '';
      // b0fk: never claim success with no content (missing key -> 401 -> '').
      if (!fixContent.trim()) {
        return NextResponse.json({ error: 'Generation failed — no content returned' }, { status: 500 });
      }
      const kpValidation = validateNoFakeData(fixContent);
      const kpMeta = getFixMetadata('knowledge_panel');
      return NextResponse.json({
        success: true,
        fix_type: 'knowledge_panel',
        content: fixContent,
        metadata: { fixType: 'knowledge_panel', industry, countryCode: resolvedCountry, businessName: businessInput, estimatedImpact: kpMeta.estimatedImpact, difficulty: kpMeta.difficulty, timeToImplement: kpMeta.timeToImplement, howToVerify: kpMeta.howToVerify, relatedSignals: kpMeta.relatedSignals, containsPlaceholders: fixContent.includes('YOUR_'), generatedAt: new Date().toISOString() },
        warning: kpValidation.valid ? undefined : '⚠️ Review this content before using — it may contain placeholder data that needs updating.',
        validationIssues: kpValidation.valid ? undefined : kpValidation.issues,
      });
    }

    // Auto-generation path (also reachable directly) → persist via the shared lib.
    // P0a: this path WRITES fixes into an account, so it requires a session and
    // the caller must own the scan. The body userId is never trusted.
    if (autoGenerated && scanId && userId) {
      const authed = createServerClient(
        process.env.NEXT_PUBLIC_SUPABASE_URL!,
        process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
        { cookies: { getAll: () => req.cookies.getAll(), setAll: () => {} } },
      );
      const { data: { user: sessionUser } } = await authed.auth.getUser();
      if (!sessionUser) {
        return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
      }
      const admin = createClient(
        process.env.NEXT_PUBLIC_SUPABASE_URL!,
        process.env.SUPABASE_SERVICE_ROLE_KEY!,
        { auth: { autoRefreshToken: false, persistSession: false } },
      );
      const { data: scanRow } = await admin
        .from('rankall_scans')
        .select('user_id')
        .eq('id', scanId)
        .maybeSingle();
      const scanOwner = (scanRow as Record<string, unknown> | null)?.user_id as string | null;
      if (!scanRow || scanOwner !== sessionUser.id) {
        return NextResponse.json({ error: 'Forbidden' }, { status: 403 });
      }
      const result = await generateFixForScan({
        scanId, fixType, userId: sessionUser.id, businessName: typeof businessInput === 'string' ? businessInput : '',
        industry, city: city ?? location, countryCode: resolvedCountry, score,
        competitorName, competitorScore, revenueGap, source: 'auto_after_scan',
      });
      return NextResponse.json({ success: result.success, generatedFixId: result.generatedFixId, fixTitle: fixTypeLabel(fixType), predictedImpact: canonicalFixImpact(fixType), skipped: result.skipped, error: result.error });
    }

    // Manual path — generate content and return it (no DB write).
    const safeName = safeBusinessName(typeof businessInput === 'string' ? businessInput : '');
    const content = await generateFixContent({ fixType, businessName: safeName, industry, location, countryCode: resolvedCountry });
    const validation = validateNoFakeData(content);
    const meta = getFixMetadata(fixType);

    return NextResponse.json({
      success: true,
      content,
      fixTitle: fixTypeLabel(fixType),
      predictedImpact: canonicalFixImpact(fixType),
      metadata: { fixType, industry, countryCode: resolvedCountry, businessName: businessInput, estimatedImpact: meta.estimatedImpact, difficulty: meta.difficulty, timeToImplement: meta.timeToImplement, howToVerify: meta.howToVerify, relatedSignals: meta.relatedSignals, containsPlaceholders: content.includes('YOUR_'), generatedAt: new Date().toISOString() },
      warning: validation.valid ? undefined : '⚠️ Review this content before using — it may contain placeholder data that needs updating.',
      validationIssues: validation.valid ? undefined : validation.issues,
    });
  } catch (error) {
    console.error("Generate fix error:", error);
    return NextResponse.json({ error: "Generation failed" }, { status: 500 });
  }
}
