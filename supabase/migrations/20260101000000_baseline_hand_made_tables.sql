-- RLS + policies exactly as on staging, applied ONLY to tables created above
-- (never touches a table that already existed).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM _baseline_preexisting WHERE t = 'cancellation_requests') THEN
    ALTER TABLE public.cancellation_requests ENABLE ROW LEVEL SECURITY;
    CREATE POLICY "Users can read own cancellation requests" ON public.cancellation_requests
      FOR SELECT USING (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM _baseline_preexisting WHERE t = 'competitor_scans') THEN
    ALTER TABLE public.competitor_scans ENABLE ROW LEVEL SECURITY;
    CREATE POLICY "Users can insert own competitor scans" ON public.competitor_scans
      FOR INSERT WITH CHECK (auth.uid() = user_id);
    CREATE POLICY "Users can read own competitor scans" ON public.competitor_scans
      FOR SELECT USING (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM _baseline_preexisting WHERE t = 'data_labels') THEN
    ALTER TABLE public.data_labels ENABLE ROW LEVEL SECURITY;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM _baseline_preexisting WHERE t = 'email_sequence_log') THEN
    ALTER TABLE public.email_sequence_log ENABLE ROW LEVEL SECURITY;
    CREATE POLICY "Users can read own email logs" ON public.email_sequence_log
      FOR SELECT USING (auth.uid() = user_id);
  END IF;
END $$;
