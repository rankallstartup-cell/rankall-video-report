-- Baseline: tables that were created by hand in the Supabase dashboard before
-- we used migrations. Copied from the staging schema on 2026-10-17, MINUS every
-- column / index / policy that a later migration adds (so the migration chain
-- rebuilds staging exactly on an empty database).
--
-- On staging and production these tables already exist, so this file changes
-- NOTHING there: tables use IF NOT EXISTS, and RLS + policies are only set up
-- for a table this file has just created. The migration pipeline also records
-- this version as already applied on both projects (supabase/migration-baseline/).
--
-- Do not edit this file to change a table — write a new migration instead.

CREATE TEMP TABLE IF NOT EXISTS _baseline_preexisting ON COMMIT DROP AS
  SELECT c.relname::text AS t
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p');

